    def test_six_reviewed_archives_preserve_printed_days_siblings_and_all_native_rows(self):
        from . import reviewed_city_dates as reviews

        archives = json.loads(REVIEWED_DATES.read_text())["archives"]
        self.assertEqual(len(archives), 6)
        grand_total = 0
        reviewed_total = 0
        pdf_count = 0
        for archive in archives:
            fixture = REVIEWED_DATE_FIXTURES / (archive["archive_id"] + ".zip")
            if not fixture.exists():
                fixture = REVIEWED_NEXTDAY_FIXTURES / fixture.name
            body = fixture.read_bytes()
            self.assertEqual(sha256(body).hexdigest(), archive["archive_id"])
            self.data = body
            self.did = self.local_archive(self.db, archive["url"], body, "city-zip")
            expected = {}
            review_documents = set()
            with zipfile.ZipFile(io.BytesIO(body)) as bundle:
                for info in bundle.infolist():
                    if info.is_dir() or not info.filename.lower().endswith(".pdf"):
                        continue
                    child = bundle.read(info)
                    did = sha256(child).hexdigest()
                    member = reviews.reviewed_member(archive, info.filename, child)
                    parsed_day = date.fromisoformat(member["printed_day"] if member else archive["archive_day"])
                    rows = list(city_reports.parse_city_pdf(child, parsed_day))
                    if member:
                        self.assertEqual(did, member["document_id"])
                        reviews.validate_rows(member, rows)
                        review_documents.add(did)
                        reviewed_total += len(rows)
                    expected[did] = rows
                    pdf_count += 1
            self.assertEqual(review_documents, {m["document_id"] for m in archive["members"]})
            before = self.count("regional_price")
            for attempt in range(2):
                with self.assertRaises(city_reports.CityZipPartialReview) as partial:
                    city_reports.publish_city_zip(
                        self.db, body, self.did, archive["url"],
                        date.fromisoformat(archive["archive_day"]),
                        processor_version=city_reports.VERSION,
                    )
                self.assertEqual(partial.exception.count, sum(map(len, expected.values())))
                self.assertEqual(len(partial.exception.failures), len(review_documents))
                self.assertEqual({f["error_type"] for f in partial.exception.failures}, {"SourceDateMismatch"})
                self.assertEqual(self.count("regional_price") - before, sum(map(len, expected.values())))
                for did, rows in expected.items():
                    actual = self.db.execute(
                        "SELECT source_locator," + ",".join(city_reports._PRICE_FIELDS) +
                        " FROM regional_price WHERE document_id=%s ORDER BY source_locator", (did,),
                    ).fetchall()
                    self.assertEqual(actual, sorted(rows, key=lambda row: row[0]))
                    categories = dict(self.db.execute(
                        "SELECT source_locator,category_path FROM regional_classification "
                        "WHERE document_id=%s", (did,),
                    ).fetchall())
                    self.assertEqual(categories, {r[0]: r[5].split(" > ") for r in rows})
                    self.assertEqual(self.db.execute(
                        "SELECT count(*) FROM published_regional_price WHERE document_id=%s", (did,),
                    ).fetchone()[0], len(rows))
                self.assertEqual(self.db.execute(
                    "SELECT count(*) FROM source_archive_member WHERE archive_id=%s", (self.did,),
                ).fetchone()[0], len(expected))
                self.assertEqual(self.db.execute(
                    "SELECT count(*) FROM ingestion_checkpoint WHERE document_id=%s "
                    "AND processor_version=%s AND step LIKE 'city-member:%%'", (self.did, city_reports.VERSION),
                ).fetchone()[0], len(expected))
                self.assertEqual(self.db.execute(
                    "SELECT count(*) FROM ingestion_checkpoint WHERE document_id=%s "
                    "AND processor_version=%s AND step LIKE 'review:%%'", (self.did, city_reports.VERSION),
                ).fetchone()[0], len(review_documents))
                if attempt == 0:
                    immutable = self.db.execute(
                        "SELECT document_id,source_locator,xmin::text FROM regional_price "
                        "WHERE document_id=ANY(%s) ORDER BY 1,2", (list(expected),),
                    ).fetchall()
                else:
                    self.assertEqual(immutable, self.db.execute(
                        "SELECT document_id,source_locator,xmin::text FROM regional_price "
                        "WHERE document_id=ANY(%s) ORDER BY 1,2", (list(expected),),
                    ).fetchall())
            grand_total += sum(map(len, expected.values()))
        self.assertEqual((grand_total, reviewed_total, pdf_count), (9028, 4330, 120))

