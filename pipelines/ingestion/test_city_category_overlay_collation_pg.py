"""Retained Sep 7 Corabastos regression for SQL category proof ordering.

The actual 198 native rows include both "row 5" and "row 50" locators.
A private ICU collation that ignores punctuation reproduces the hosted
`en_US.utf8` ordering difference. Both SQL digests and the worker's saved-plan
comparison must use C ordering; all source, category and monetary guards stay active.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import unittest
import uuid
import zipfile
from datetime import date
from pathlib import Path

import psycopg
from psycopg import sql
from psycopg.types.json import Jsonb

from . import city_category_overlay as overlay, city_discovery, city_reports

ROOT = Path(__file__).resolve().parent
FIX = ROOT / "testdata/city_category_overlay_20260907"
SQL057 = ROOT / "migrations/20261005_057_city_category_overlay.sql"
SQL058 = ROOT / "migrations/20261005_058_city_category_proof_collation.sql"
SQL059 = ROOT / "migrations/20261005_059_city_category_adjudication.sql"


@unittest.skipUnless(
    os.environ.get("AGRO_REFERENCE_TEST_DSN"), "Private PostgreSQL socket fixture required"
)
class CityCategoryCollationPg(unittest.TestCase):
    def connect(self, *, autocommit=False):
        db = psycopg.connect(
            self.dsn,
            autocommit=autocommit,
            options="-c statement_timeout=20000 -c lock_timeout=8000",
        )
        if (
            not db.info.host.startswith("/tmp/agro-")
            or db.execute("SELECT inet_server_addr()").fetchone()[0] is not None
        ):
            db.close()
            raise RuntimeError("Category regression requires private local PostgreSQL")
        return db

    def setUp(self):
        self.dsn = os.environ["AGRO_REFERENCE_TEST_DSN"]
        self.schema = "category_collation_" + uuid.uuid4().hex[:12]
        self.fixture = json.loads((FIX / "corabastos_198_rows.json").read_text())
        self.parent = self.fixture["parent"]
        self.child = self.fixture["child"]
        self.data = (FIX / (self.parent["id"] + ".zip")).read_bytes()
        self.pdf = (FIX / (self.child["id"] + ".pdf")).read_bytes()
        self.assertEqual(hashlib.sha256(self.data).hexdigest(), self.parent["id"])
        self.assertEqual(hashlib.sha256(self.pdf).hexdigest(), self.child["id"])
        with zipfile.ZipFile(io.BytesIO(self.data)) as archive:
            self.assertEqual(archive.read(self.fixture["entry_name"]), self.pdf)
        self.native = list(
            city_reports.parse_city_pdf(
                self.pdf, city_discovery.archive_day(self.parent["source_url"])
            )
        )
        self.assertEqual(len(self.native), 198)
        self.assertEqual(city_reports.VERSION, "city-v8")
        self.admin = self.connect(autocommit=True)
        self.addCleanup(self.cleanup_schema)
        self.admin.execute(
            "DO $$ BEGIN CREATE ROLE agro_reader; EXCEPTION WHEN duplicate_object THEN NULL; END $$"
        )
        self.admin.execute(
            "DO $$ BEGIN CREATE ROLE agro_ingestor; EXCEPTION WHEN duplicate_object THEN NULL; END $$"
        )
        self.admin.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(self.schema)))
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        self.admin.execute(
            "CREATE COLLATION shifted_locator (provider=icu,locale='en-u-ka-shifted')"
        )
        self.admin.execute(
            """CREATE TABLE source_document(id text PRIMARY KEY,kind text NOT NULL,
                media_type text NOT NULL,source_url text NOT NULL,metadata jsonb NOT NULL,
                content bytea NOT NULL);
            CREATE TABLE source_archive_member(archive_id text,entry_name text,
                document_id text,PRIMARY KEY(archive_id,entry_name));
            CREATE TABLE regional_price(document_id text,
                source_locator text COLLATE shifted_locator,observed_on date,
                product_id text,product_name text,market_name text,category text,
                presentation text,quantity numeric,source_unit text,round integer,
                round_label text,min_price numeric,max_price numeric,unit text,
                min_unit_price numeric,max_unit_price numeric,source_page integer,
                PRIMARY KEY(document_id,source_locator));
            CREATE TABLE regional_classification(document_id text,
                source_locator text COLLATE shifted_locator,category_path text[],
                PRIMARY KEY(document_id,source_locator));
            CREATE TABLE city_pdf_publication_conflict(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                document_id text,archive_id text,
                entry_name text,processor_version text,native_sha256 text,
                stored_sha256 text,details jsonb,
                UNIQUE(document_id,processor_version,native_sha256,stored_sha256));
            CREATE TABLE regional_price_product_correction(document_id text,
                source_locator text,old_product_id text,old_product_name text,
                corrected_product_id text,corrected_product_name text,
                PRIMARY KEY(document_id,source_locator));
            CREATE TABLE ingestion_checkpoint(document_id text,processor_version text,
                step text,records integer,PRIMARY KEY(document_id,processor_version,step));
            CREATE VIEW published_regional_price AS SELECT r.* FROM regional_price r
                WHERE NOT EXISTS (SELECT 1 FROM city_pdf_publication_conflict c
                                  WHERE c.document_id=r.document_id);
            CREATE FUNCTION prevent_history_removal() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN RAISE EXCEPTION 'retained row cannot change'; END $$;"""
        )
        # Production stores both raw and overlay locators with the database's
        # default collation. Exercise the saved-plan verifier under the same
        # non-C ordering rather than accidentally testing C-ordered overlays.
        migration = SQL057.read_text()
        locator_declaration = " source_locator text NOT NULL,"
        self.assertEqual(migration.count(locator_declaration), 1)
        self.admin.execute(
            migration.replace(
                locator_declaration,
                " source_locator text COLLATE shifted_locator NOT NULL,",
            )
        )
        self.admin.execute(
            "INSERT INTO source_document VALUES(%s,%s,%s,%s,%s,%s)",
            (
                self.parent["id"],
                self.parent["kind"],
                self.parent["media_type"],
                self.parent["source_url"],
                Jsonb(self.parent["metadata"]),
                self.data,
            ),
        )
        self.admin.execute(
            "INSERT INTO source_document VALUES(%s,%s,%s,%s,%s,%s)",
            (
                self.child["id"],
                self.child["kind"],
                self.child["media_type"],
                self.child["source_url"],
                Jsonb(self.child["metadata"]),
                self.pdf,
            ),
        )
        self.admin.execute(
            "INSERT INTO source_archive_member VALUES(%s,%s,%s)",
            (self.parent["id"], self.fixture["entry_name"], self.child["id"]),
        )
        for raw in self.fixture["raw_rows"]:
            fields = [raw[field] for field in overlay.FIELDS]
            fields[1] = date.fromisoformat(fields[1])
            self.admin.execute(
                "INSERT INTO regional_price VALUES(" + ",".join(["%s"] * 18) + ")",
                (self.child["id"], *fields),
            )
        for locator, path in self.fixture["classifications"].items():
            self.admin.execute(
                "INSERT INTO regional_classification VALUES(%s,%s,%s)",
                (self.child["id"], locator, path),
            )
        self.admin.execute(
            sql.SQL("GRANT USAGE ON SCHEMA {} TO agro_ingestor").format(
                sql.Identifier(self.schema)
            )
        )
        self.admin.execute(
            "GRANT SELECT ON source_document,source_archive_member,regional_price,"
            "regional_classification,regional_price_product_correction,"
            "city_pdf_publication_conflict TO agro_ingestor"
        )
        self.admin.execute(
            "GRANT SELECT,INSERT ON regional_price_category_overlay,"
            "city_category_overlay_proof TO agro_ingestor"
        )
        self.admin.execute("RESET search_path")

    def cleanup_schema(self):
        self.admin.execute(
            sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(self.schema))
        )
        self.admin.close()

    def ingestor(self):
        db = self.connect()
        db.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        db.execute("SET ROLE agro_ingestor")
        self.addCleanup(db.close)
        return db

    def apply(self, db, *, native=None, archive_id=None, source_url=None):
        rows = self.native if native is None else native
        proposal = overlay.apply_category_overlay(
            db,
            parent_zip=self.data,
            archive_id=archive_id or self.parent["id"],
            entry_name=self.fixture["entry_name"],
            child_pdf=self.pdf,
            document_id=self.child["id"],
            source_url=source_url or self.parent["source_url"],
            native_rows=rows,
        )
        # The real publisher reads the proof back before accepting category
        # parity. An insert-only test misses the production ordering failure.
        overlay.load_verified_category_overlay(db, self.child["id"], rows, proposal)
        return proposal

    def counts(self):
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        result = self.admin.execute(
            "SELECT (SELECT count(*) FROM regional_price_category_overlay),"
            "(SELECT count(*) FROM city_category_overlay_proof),"
            "(SELECT count(*) FROM regional_price)"
        ).fetchone()
        self.admin.execute("RESET search_path")
        return result

    def raw_digest(self):
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        rows = self.admin.execute(
            "SELECT row_to_json(r)::text FROM "
            "(SELECT * FROM regional_price ORDER BY source_locator COLLATE \"C\") r"
        ).fetchall()
        self.admin.execute("RESET search_path")
        return hashlib.sha256("".join(row[0] for row in rows).encode()).hexdigest()

    def fix(self):
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        self.admin.execute(SQL058.read_text())
        self.admin.execute(SQL059.read_text())
        self.admin.execute("RESET search_path")

    def test_full_198_native_rows_fail_old_collation_then_pass_new(self):
        did = self.child["id"]
        raw_before = self.raw_digest()
        with self.ingestor() as db:
            with self.assertRaisesRegex(
                psycopg.errors.RaiseException, "Whole-city category proof is incomplete"
            ):
                with db.transaction():
                    self.apply(db)
        self.assertEqual(self.counts(), (0, 0, 198))
        self.fix()
        with self.ingestor() as db:
            with db.transaction():
                first = self.apply(db)
            with db.transaction():
                second = self.apply(db)
        self.assertEqual(first["proof"]["proof_id"], second["proof"]["proof_id"])
        self.assertEqual(self.counts(), (198, 1, 198))
        self.assertEqual(self.raw_digest(), raw_before)
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        self.assertEqual(
            self.admin.execute(
                "SELECT count(*) FROM verified_regional_category_overlay WHERE document_id=%s",
                (did,),
            ).fetchone()[0],
            198,
        )
        self.assertEqual(
            self.admin.execute(
                "SELECT count(*) FROM regional_price r JOIN verified_regional_category_overlay o "
                "USING(document_id,source_locator) "
                "WHERE r.category=o.corrected_category"
            ).fetchone()[0],
            0,
        )
        self.admin.execute("RESET search_path")

    def test_worker_default_order_rejects_exact_sql_valid_plan(self):
        """SQL058 alone is insufficient when the worker sorts overlays differently."""
        self.fix()
        raw_before = self.raw_digest()

        class PreviousWorkerOrder:
            def __init__(self, db):
                self.db = db

            def __getattr__(self, name):
                return getattr(self.db, name)

            def execute(self, query, params=None):
                if (
                    isinstance(query, str)
                    and "FROM regional_price_category_overlay" in query
                    and "ORDER BY source_locator COLLATE \"C\"" in query
                ):
                    query = query.replace(
                        "ORDER BY source_locator COLLATE \"C\"",
                        "ORDER BY source_locator",
                    )
                return self.db.execute(query, params)

        with self.ingestor() as db:
            with self.assertRaisesRegex(
                overlay.Ineligible, "Existing category overlays differ"
            ):
                with db.transaction():
                    self.apply(PreviousWorkerOrder(db))
        self.assertEqual(self.counts(), (0, 0, 198))
        with self.ingestor() as db:
            with db.transaction():
                self.apply(db)
            default_order = db.execute(
                "SELECT source_locator FROM regional_price_category_overlay "
                "ORDER BY source_locator"
            ).fetchall()
            c_order = db.execute(
                "SELECT source_locator FROM regional_price_category_overlay "
                "ORDER BY source_locator COLLATE \"C\""
            ).fetchall()
            self.assertNotEqual(default_order, c_order)
            self.assertEqual(c_order, sorted(c_order))
            with db.transaction():
                self.apply(db)
        self.assertEqual(self.counts(), (198, 1, 198))
        self.assertEqual(self.raw_digest(), raw_before)

    def test_crash_rollback_and_source_monetary_guards(self):
        raw_before = self.raw_digest()
        self.fix()
        with self.ingestor() as db:
            with self.assertRaisesRegex(RuntimeError, "simulated crash"):
                with db.transaction():
                    self.apply(db)
                    raise RuntimeError("simulated crash")
        self.assertEqual(self.counts(), (0, 0, 198))
        self.assertEqual(self.raw_digest(), raw_before)
        with self.ingestor() as db:
            altered = list(self.native)
            altered[0] = (*altered[0][:-1], altered[0][-1] + 1)
            with self.assertRaises(overlay.Ineligible):
                with db.transaction():
                    self.apply(db, native=altered)
            with self.assertRaises(overlay.Ineligible):
                with db.transaction():
                    self.apply(db, archive_id="0" * 64)
            with self.assertRaises(overlay.Ineligible):
                with db.transaction():
                    self.apply(db, source_url=self.parent["source_url"] + "?changed=1")
        self.assertEqual(self.counts(), (0, 0, 198))
        self.admin.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        locator = self.native[0][0]
        old_category, old_price = self.admin.execute(
            "SELECT category,min_price FROM regional_price "
            "WHERE document_id=%s AND source_locator=%s",
            (self.child["id"], locator),
        ).fetchone()
        try:
            self.admin.execute(
                "UPDATE regional_price SET category='wrong-category' "
                "WHERE document_id=%s AND source_locator=%s",
                (self.child["id"], locator),
            )
            with self.ingestor() as db:
                with self.assertRaises(overlay.Ineligible):
                    with db.transaction():
                        self.apply(db)
        finally:
            self.admin.execute(
                "UPDATE regional_price SET category=%s WHERE document_id=%s "
                "AND source_locator=%s",
                (old_category, self.child["id"], locator),
            )
        try:
            self.admin.execute(
                "UPDATE regional_price SET min_price=min_price+1 "
                "WHERE document_id=%s AND source_locator=%s",
                (self.child["id"], locator),
            )
            with self.ingestor() as db:
                with self.assertRaises(overlay.Ineligible):
                    with db.transaction():
                        self.apply(db)
        finally:
            self.admin.execute(
                "UPDATE regional_price SET min_price=%s WHERE document_id=%s "
                "AND source_locator=%s",
                (old_price, self.child["id"], locator),
            )
        self.assertEqual(self.counts(), (0, 0, 198))

    def test_migration_changes_only_two_digest_orderings(self):
        source = SQL057.read_text()
        old = source[
            source.index("CREATE OR REPLACE FUNCTION validate_city_category_overlay_proof()"):source.index(
                "DROP TRIGGER IF EXISTS validate_city_category_overlay_proof"
            )
        ]
        new = SQL058.read_text()
        new = new[new.index("CREATE OR REPLACE FUNCTION validate_city_category_overlay_proof()"):]
        needle = "'' ORDER BY r.source_locator)"
        self.assertEqual(old.count(needle), 2)
        self.assertEqual(
            new,
            old.replace(needle, "'' ORDER BY r.source_locator COLLATE \"C\")"),
        )
