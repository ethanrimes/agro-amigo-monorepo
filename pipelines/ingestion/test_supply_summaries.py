def fixture():
    with zipfile.ZipFile(FIXTURES / "originals/mayoristas_diciembre_31_2021.zip") as z:
        return z.read(
            "mayoristas_diciembre_31_2021-Consolidado precios mínimos y máximos.xlsx"
        )


def mutate(change):
    book = openpyxl.load_workbook(io.BytesIO(fixture()))
    change(book["Abastecimiento"])
    out = io.BytesIO()
    book.save(out)
    book.close()
    return out.getvalue()


class NativeSupplySummaries(unittest.TestCase):
    def test_two_independent_original_cell_oracles(self):
        # Literal source anchors, not values generated by the parser under test.
        originals = [
            (
                "mayoristas_diciembre_31_2021.zip",
                "mayoristas_diciembre_31_2021-Consolidado precios mínimos y máximos.xlsx",
                1560,
                1268,
                "BA12",
                date(2021, 12, 30),
                394,
            ),
            (
                "anexos-diarios-semanal.zip",
                "mayoristas_noviembre_26_2021.xlsx",
                510,
                432,
                "R12",
                date(2021, 11, 25),
                370,
            ),
        ]
        for filename, member, total, reported, cell, day, tonnes in originals:
            with (
                self.subTest(filename=filename),
                zipfile.ZipFile(FIXTURES / "originals" / filename) as z,
            ):
                rows = adapter.parse(z.read(member), date(2021, 12, 31))
                self.assertEqual(len(rows), total)
                self.assertEqual(
                    sum(r["details"]["quantity_tonnes"] is not None for r in rows),
                    reported,
                )
                anchor = next(r for r in rows if r["details"]["cell"] == cell)
                self.assertEqual(
                    (
                        anchor["name"],
                        anchor["observed_on"],
                        anchor["details"]["quantity_tonnes"],
                    ),
                    ("Armenia, Mercar", day, tonnes),
                )
                self.assertEqual(anchor["details"]["aggregation_level"], "market_total")
                self.assertEqual(anchor["details"]["unit"], "t")
                self.assertTrue(anchor["details"]["non_additive"])
                self.assertTrue(anchor["details"]["provisional"])
                self.assertEqual(anchor["kind"], "supply-daily-summary")
                total_row = next(r for r in rows if r["details"]["cell"] == "B11")
                self.assertEqual(
                    total_row["details"]["aggregation_level"], "reported_markets_total"
                )
                self.assertAlmostEqual(
                    total_row["details"]["quantity_tonnes"], 21818.383
                )
                self.assertNotIn("price", anchor)

    def test_entire_19_original_corpus_matches_independent_native_oracles(self):
        oracle = json.loads(
            (FIXTURES / "supply-summaries/native-oracles.json").read_text()
        )
        self.assertEqual(
            oracle["totals"],
            {
                "cells": 20400,
                "reported_cells": 16660,
                "blank_cells": 3740,
                "explicit_zeroes": 47,
                "workbooks": 19,
                "errors": 0,
            },
        )
        checked = 0
        for src in oracle["originals"]:
            with zipfile.ZipFile(
                FIXTURES / "originals" / src["archive_url"].rsplit("/", 1)[-1]
            ) as z:
                body = z.read(src["member"])
                rows = adapter.parse(body)
                book = openpyxl.load_workbook(io.BytesIO(body), data_only=True)
                try:
                    sheet = book["Abastecimiento"]
                    self.assertEqual(len(rows), src["cells"])
                    for row in rows:
                        d = row["details"]
                        cell = sheet[d["cell"]]
                        self.assertEqual(
                            (row["name"], row["observed_on"], d["quantity_tonnes"]),
                            (
                                sheet.cell(d["row"], 1).value,
                                sheet.cell(9, d["column"]).value.date(),
                                cell.value,
                            ),
                        )
                        checked += 1
                finally:
                    book.close()
        self.assertEqual(checked, 20400)

    def test_blank_explicit_zero_and_percentage_are_distinct(self):
        rows = adapter.parse(mutate(lambda s: s.__setitem__("BA12", 0)))
        a = next(r for r in rows if r["details"]["cell"] == "BA12")
        b = next(r for r in rows if r["details"]["cell"] == "AV12")
        self.assertEqual(
            (a["details"]["quantity_tonnes"], a["details"]["availability"]),
            (0, "reported"),
        )
        self.assertEqual(
            (b["details"]["quantity_tonnes"], b["details"]["availability"]),
            (None, "not_reported"),
        )
        self.assertEqual(a["details"]["variations"][0]["unit"], "percentage_points")
        self.assertAlmostEqual(
            a["details"]["variations"][0]["value"], 1.285347043701801
        )
        self.assertEqual(a["details"]["variations"][0]["compared_on"], "2021-12-29")
        self.assertEqual(a["details"]["variations"][0]["source_cell"], "BB12")
        self.assertFalse(
            any(r["details"]["cell"].startswith(("BB", "BC")) for r in rows)
        )

    def test_duplicate_market_and_date_labels_are_not_inferred(self):
        for action in [
            lambda s: s.__setitem__("A13", s["A12"].value),
            lambda s: s.__setitem__("C9", s["B9"].value),
        ]:
            with self.assertRaises(ValueError):
                adapter.parse(mutate(action))

    def test_units_caption_future_and_archive_bounds_fail_closed(self):
        for action in [
            lambda s: s.__setitem__("BA10", "Kilogramos"),
            lambda s: s.__setitem__("A5", "Noviembre 9 a Diciembre 29 de 2021*"),
            lambda s: s.__setitem__("B7", "Información definitiva"),
        ]:
            with self.assertRaises(ValueError):
                adapter.parse(mutate(action))
        with self.assertRaises(worker.SourceDateMismatch):
            adapter.parse(fixture(), date(2021, 12, 29))
        with (
            patch.object(worker, "today", return_value=date(2021, 12, 29)),
            self.assertRaises(worker.SourceDateMismatch),
        ):
            adapter.parse(fixture())

    def test_invalid_quantity_and_quoted_percent_are_not_repaired(self):
        def quoted(s):
            s["BB12"].number_format = '0.0"%"'

        for action in [
            lambda s: s.__setitem__("BA12", -1),
            lambda s: s.__setitem__("BA12", "394 aprox."),
            lambda s: s.__setitem__("BA12", True),
            quoted,
        ]:
            with self.assertRaises(ValueError):
                adapter.parse(mutate(action))

    def test_period_rollover_resolves_explicit_caption_only(self):
        self.assertEqual(
            adapter._period("Diciembre 29 a Enero 2 de 2022*"),
            (date(2021, 12, 29), date(2022, 1, 2)),
        )
        with self.assertRaises(ValueError):
            adapter._period("29 a 2*")

    def test_unrelated_monthly_layout_remains_original_only(self):
        self.assertEqual(
            adapter.parse(
                mutate(
                    lambda s: s.__setitem__("A4", "Variación mensual de abastecimiento")
                )
            ),
            [],
        )
        self.assertEqual(adapter.parse(b"not a supported native workbook"), [])

    def test_recognized_but_truncated_daily_header_is_reviewed(self):
        book = openpyxl.Workbook()
        sheet = book.active
        sheet.title = "Abastecimiento"
        sheet["A4"] = (
            "Toneladas de alimentos ingresados diariamente, según ciudad y mercado mayorista (29 mercados)"
        )
        out = io.BytesIO()
        book.save(out)
        book.close()
        with self.assertRaisesRegex(ValueError, "Incomplete recognized"):
            adapter.parse(out.getvalue())

    def test_versions_trigger_automatic_replay(self):
        self.assertEqual(worker.parser_version("supply-reference"), adapter.VERSION)
        self.assertTrue(worker.parser_version("daily-zip").startswith("daily-zip-v3:"))
        self.assertIn("pipelines/ingestion/supply_summaries.py", worker.RELEASE_FILES)


@unittest.skipUnless(
    os.environ.get("AGRO_DAILY_ZIP_POSTGRES_TEST") == "1", "isolated PostgreSQL opt-in"
)
class SupplySummaryPostgres(unittest.TestCase):
    def setUp(self):
        self.db = worker.connect()
        self.addCleanup(self.db.close)
        self.db.execute("SET search_path=pg_temp")
        self.db.execute("SET statement_timeout='15s'")
        self.db.execute(
            "CREATE TEMP TABLE input_reference_row(document_id text,source_locator text,kind text,observed_on date,name text,category text,details jsonb,PRIMARY KEY(document_id,source_locator))"
        )

    def test_evidence_api_queries_return_tonnes_scope_and_missing_cells(self):
        import re

        adapter.publish_rows(self.db, adapter.parse(fixture()), "first")
        source = (
            Path(__file__).resolve().parents[2] / "apps/web/src/lib/server/planning.ts"
        ).read_text()
        summary_sql = re.search(
            r"`(SELECT count\(\*\)::int cells,.*?)`", source, re.DOTALL
        )[1]
        row_sql = re.search(
            r"`(SELECT kind,observed_on,name,category,source_locator,.*?)`",
            source,
            re.DOTALL,
        )[1]
        self.assertEqual(
            self.db.execute(summary_sql.replace("$1", "%s"), ("first",)).fetchone(),
            (1560, 1268, "2021-11-09", "2021-12-30", "Abastecimiento"),
        )
        locator = "Abastecimiento!row 12,col 53; " + adapter.VERSION
        sql = row_sql.replace("$1", "%s").replace("$2", "%s")
        rows = self.db.execute(sql, ("first", locator, locator)).fetchall()
        self.assertEqual(len(rows), 1)
        self.assertEqual(
            (rows[0][0], rows[0][5], rows[0][6], rows[0][7]),
            ("supply-daily-summary", "t", 394, "market_total"),
        )

    def test_cell_publication_is_idempotent_preserves_documents_and_outer_rollback(
        self,
    ):
        rows = adapter.parse(fixture())
        with self.db.transaction():
            self.assertEqual(adapter.publish_rows(self.db, rows, "first"), 1560)
        self.assertEqual(adapter.publish_rows(self.db, rows, "first"), 1560)
        self.assertEqual(
            self.db.execute("SELECT count(*) FROM input_reference_row").fetchone(),
            (1560,),
        )
        self.assertEqual(
            self.db.execute(
                "SELECT kind,details->>'unit',details->>'quantity_tonnes' FROM input_reference_row WHERE document_id='first' AND details->>'cell'='BA12'"
            ).fetchone(),
            ("supply-daily-summary", "t", "394"),
        )
        try:
            with self.db.transaction():
                adapter.publish_rows(self.db, rows, "second")
                raise RuntimeError("rollback")
        except RuntimeError:
            pass
        self.assertEqual(
            self.db.execute("SELECT count(*) FROM input_reference_row").fetchone(),
            (1560,),
        )
        adapter.publish_rows(self.db, rows, "second")
        self.assertEqual(
            self.db.execute(
                "SELECT count(DISTINCT document_id) FROM input_reference_row"
            ).fetchone(),
            (2,),
        )
        self.assertEqual(
            self.db.execute(
                "SELECT count(*) FROM input_reference_row WHERE details->>'availability'='not_reported'"
            ).fetchone(),
            (584,),
        )


