    def connect(self, *, autocommit=False):
        db = psycopg.connect(
            self.dsn,
            autocommit=autocommit,
            options="-c statement_timeout=15000 -c lock_timeout=12000",
        )
        if db.execute("SELECT inet_server_addr()").fetchone()[
            0
        ] is not None or not db.info.host.startswith("/tmp/agro-"):
            db.close()
            raise RuntimeError(
                "Category overlay tests require a local private Unix socket"
            )
        return db

    def close_schema(self):
        self.db.execute(f"DROP SCHEMA IF EXISTS {self.schema} CASCADE")
        self.db.close()

    def child_rows(self, child):
        return list(
            city_reports.parse_city_pdf(
                child["bytes"], city_discovery.archive_day(self.parent["source_url"])
            )
        )

    def apply(self, db, child):
        return overlay.apply_category_overlay(
            db,
            parent_zip=self.parent_bytes,
            archive_id=self.parent["id"],
            entry_name=child["entry_name"],
            child_pdf=child["bytes"],
            document_id=child["original"]["id"],
            source_url=self.parent["source_url"],
            native_rows=self.child_rows(child),
        )

    def test_two_originals_complete_current_parser_and_raw_immutable(self):
        self.assertEqual(city_reports.VERSION, "city-v8")
        with self.connect() as db:
            db.execute(f"SET search_path TO {self.schema},public")
            for child, count in zip(self.manifest["children"], (46, 31), strict=True):
                did = child["original"]["id"]
                before = db.execute(
                    "SELECT count(*),md5(string_agg(source_locator||category,'' ORDER BY source_locator)) "
                    "FROM regional_price WHERE document_id=%s",
                    (did,),
                ).fetchone()
                result = self.apply(db, child)
                self.assertEqual(len(result["rows"]), count)
                verified = overlay.load_verified_category_overlay(
                    db, did, self.child_rows(child), result
                )
                self.assertEqual(len(verified), count)
                self.assertTrue(all(isinstance(value, tuple) for value in verified.values()))
                self.assertTrue(all(
                    len(value) == 2 and all(isinstance(part, str) for part in value)
                    for value in verified.values()
                ))
                self.assertTrue(all(isinstance(value, tuple) for value in verified.values()))
                self.assertTrue(all(
                    len(value) == 2 and all(isinstance(part, str) for part in value)
                    for value in verified.values()
                ))
                self.assertEqual(
                    db.execute(
                        "SELECT count(*) FROM resolved_regional_price WHERE document_id=%s "
                        "AND category LIKE '%% > %%'",
                        (did,),
                    ).fetchone()[0],
                    count,
                )
                after = db.execute(
                    "SELECT count(*),md5(string_agg(source_locator||category,'' ORDER BY source_locator)) "
                    "FROM regional_price WHERE document_id=%s",
                    (did,),
                ).fetchone()
                self.assertEqual(before, after)
                replay = self.apply(db, child)
                self.assertEqual(
                    replay["proof"]["proof_id"], result["proof"]["proof_id"]
                )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_category_overlay_proof"
                ).fetchone()[0],
                2,
            )
            db.rollback()

