    def test_distinct_same_parent_entry_alias_requires_both_exact_member_bytes(self):
        child = self.manifest["children"][0]
        did = child["original"]["id"]
        alias = "Barranquilla, Barranquillita copied name-07-09-2026.pdf"
        primary = child["entry_name"]
        archive = io.BytesIO()
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zipfile_out:
            zipfile_out.writestr(primary, child["bytes"])
            zipfile_out.writestr(alias, child["bytes"])
        parent = archive.getvalue()
        parent_id = hashlib.sha256(parent).hexdigest()
        with self.connect() as db:
            db.execute(f"SET search_path TO {self.schema},public")
            db.execute(
                "INSERT INTO source_document VALUES(%s,'original','application/zip',%s,%s,%s)",
                (
                    parent_id,
                    self.parent["source_url"],
                    Jsonb({"retention": "permanent"}),
                    parent,
                ),
            )
            db.execute(
                "UPDATE source_document SET metadata=%s WHERE id=%s",
                (
                    Jsonb(
                        {
                            "ingestion_kind": "city-pdf",
                            "archive_entry": primary,
                            "parents": [parent_id],
                        }
                    ),
                    did,
                ),
            )
            for entry in (primary, alias):
                db.execute(
                    "INSERT INTO source_archive_member VALUES(%s,%s,%s)",
                    (parent_id, entry, did),
                )
            native = self.child_rows(child)
            primary_result = overlay.apply_category_overlay(
                db,
                parent_zip=parent,
                archive_id=parent_id,
                entry_name=primary,
                child_pdf=child["bytes"],
                document_id=did,
                source_url=self.parent["source_url"],
                native_rows=native,
            )
            result = overlay.apply_category_overlay(
                db,
                parent_zip=parent,
                archive_id=parent_id,
                entry_name=alias,
                child_pdf=child["bytes"],
                document_id=did,
                source_url=self.parent["source_url"],
                native_rows=native,
            )
            self.assertEqual(result["proof"]["entry_name"], primary)
            self.assertEqual(result["proof"]["requested_entry_name"], alias)
            self.assertNotEqual(
                primary_result["proof"]["proof_id"], result["proof"]["proof_id"]
            )
            self.assertEqual(
                len(overlay.load_verified_category_overlay(db, did, native, result)), 46
            )
            self.assertEqual(
                overlay.apply_category_overlay(
                    db,
                    parent_zip=parent,
                    archive_id=parent_id,
                    entry_name=primary,
                    child_pdf=child["bytes"],
                    document_id=did,
                    source_url=self.parent["source_url"],
                    native_rows=native,
                )["proof"]["proof_id"],
                primary_result["proof"]["proof_id"],
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_category_overlay_proof"
                ).fetchone()[0],
                2,
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM regional_price_category_overlay"
                ).fetchone()[0],
                46,
            )
            db.commit()
        with self.connect() as db:
            db.execute(f"SET search_path TO {self.schema},public")
            self.assertEqual(
                overlay.apply_category_overlay(
                    db,
                    parent_zip=parent,
                    archive_id=parent_id,
                    entry_name=primary,
                    child_pdf=child["bytes"],
                    document_id=did,
                    source_url=self.parent["source_url"],
                    native_rows=self.child_rows(child),
                )["proof"]["proof_id"],
                primary_result["proof"]["proof_id"],
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_category_overlay_proof"
                ).fetchone()[0],
                2,
            )
            db.rollback()
        # A second name pointing to different bytes is not an alias, even if
        # someone inserts a misleading member-to-DID row in a local fixture.
        divergent = io.BytesIO()
        with zipfile.ZipFile(divergent, "w", zipfile.ZIP_DEFLATED) as zipfile_out:
            zipfile_out.writestr(primary, child["bytes"])
            zipfile_out.writestr(alias, b"not the retained child")
        bad_parent = divergent.getvalue()
        bad_id = hashlib.sha256(bad_parent).hexdigest()
        with self.connect() as db:
            db.execute(f"SET search_path TO {self.schema},public")
            db.execute(
                "INSERT INTO source_document VALUES(%s,'original','application/zip',%s,%s,%s)",
                (
                    bad_id,
                    self.parent["source_url"],
                    Jsonb({"retention": "permanent"}),
                    bad_parent,
                ),
            )
            db.execute(
                "UPDATE source_document SET metadata=%s WHERE id=%s",
                (
                    Jsonb(
                        {
                            "ingestion_kind": "city-pdf",
                            "archive_entry": primary,
                            "parents": [bad_id],
                        }
                    ),
                    did,
                ),
            )
            for entry in (primary, alias):
                db.execute(
                    "INSERT INTO source_archive_member VALUES(%s,%s,%s)",
                    (bad_id, entry, did),
                )
            with self.assertRaises(overlay.Ineligible):
                overlay.apply_category_overlay(
                    db,
                    parent_zip=bad_parent,
                    archive_id=bad_id,
                    entry_name=alias,
                    child_pdf=child["bytes"],
                    document_id=did,
                    source_url=self.parent["source_url"],
                    native_rows=self.child_rows(child),
                )
            db.rollback()


