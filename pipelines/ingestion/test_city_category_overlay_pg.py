    def test_two_session_advisory_lock_and_single_full_attestation(self):
        child = self.manifest["children"][0]
        entered = threading.Event()
        release = threading.Event()
        second_started = threading.Event()
        original = overlay.plan

        def delayed_plan(*args, **kwargs):
            if threading.current_thread().name == "first-publisher":
                entered.set()
                if not release.wait(10):
                    raise RuntimeError("test lock timeout")
            return original(*args, **kwargs)

        def run_first():
            threading.current_thread().name = "first-publisher"
            with self.connect() as db:
                db.execute(f"SET search_path TO {self.schema},public")
                result = self.apply(db, child)
                db.commit()
                return result["proof"]["proof_id"]

        def run_second():
            second_started.set()
            with self.connect() as db:
                db.execute(f"SET search_path TO {self.schema},public")
                result = self.apply(db, child)
                db.commit()
                return result["proof"]["proof_id"]

        with (
            patch.object(overlay, "plan", side_effect=delayed_plan),
            ThreadPoolExecutor(max_workers=2) as pool,
        ):
            first = pool.submit(run_first)
            self.assertTrue(entered.wait(8))
            second = pool.submit(run_second)
            self.assertTrue(second_started.wait(3))
            time.sleep(0.15)
            self.assertFalse(second.done())
            release.set()
            self.assertEqual(first.result(timeout=10), second.result(timeout=10))
        with self.connect() as db:
            db.execute(f"SET search_path TO {self.schema},public")
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_category_overlay_proof"
                ).fetchone()[0],
                1,
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM regional_price_category_overlay"
                ).fetchone()[0],
                46,
            )
            db.rollback()

