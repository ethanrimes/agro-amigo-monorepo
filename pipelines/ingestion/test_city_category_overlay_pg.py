    def test_actual_zip_replay_checkpoints_both_legacy_children(self):
        # The two retained children are archive members 2 and 3. Precheckpoint
        # unrelated member 1 and defer before member 4, so the real ZIP loop,
        # native parser, publication hook and checkpoint boundary all execute.
        from . import worker
        from .resumable_inputs import WorkDeferred

        with zipfile.ZipFile(io.BytesIO(self.parent_bytes)) as archive:
            members = [
                member
                for member in archive.infolist()
                if not member.is_dir() and member.filename.lower().endswith(".pdf")
            ]
        self.assertEqual(
            [member.filename for member in members[1:3]],
            [child["entry_name"] for child in self.manifest["children"]],
        )
        with self.connect(autocommit=True) as db:
            db.execute(f"SET search_path TO {self.schema},public")
            db.execute(
                "INSERT INTO ingestion_checkpoint VALUES(%s,%s,%s,0)",
                (
                    self.parent["id"],
                    city_reports.VERSION,
                    city_reports._member_step(
                        members[0],
                        city_discovery.archive_day(self.parent["source_url"]),
                    ),
                ),
            )
            before = db.execute(
                "SELECT count(*),md5(string_agg(source_locator||category,'' ORDER BY document_id,source_locator)) "
                "FROM regional_price"
            ).fetchone()
            token = worker.RUN_DEADLINE.set(150)
            try:
                with (
                    patch.object(
                        worker,
                        "archive",
                        side_effect=lambda _db, _url, body, *_args, **_kwargs: (
                            hashlib.sha256(body).hexdigest()
                        ),
                    ),
                    patch("pipelines.ingestion.pdf_sources.extract_pages"),
                    patch.object(city_reports, "save_classifications"),
                    patch.object(city_reports, "_bulk_insert"),
                    patch.object(
                        city_reports.time,
                        "monotonic",
                        side_effect=lambda: (
                            200
                            if db.execute(
                                "SELECT count(*) FROM ingestion_checkpoint WHERE document_id=%s",
                                (self.parent["id"],),
                            ).fetchone()[0]
                            >= 3
                            else 100
                        ),
                    ),
                    self.assertRaises(WorkDeferred),
                ):
                    city_reports.publish_city_zip(
                        db,
                        self.parent_bytes,
                        self.parent["id"],
                        self.parent["source_url"],
                        city_discovery.archive_day(self.parent["source_url"]),
                    )
            finally:
                worker.RUN_DEADLINE.reset(token)
            self.assertEqual(
                db.execute(
                    "SELECT count(*),coalesce(sum(records),0) FROM ingestion_checkpoint "
                    "WHERE document_id=%s",
                    (self.parent["id"],),
                ).fetchone(),
                (3, 77),
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_category_overlay_proof"
                ).fetchone()[0],
                2,
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM verified_regional_category_overlay"
                ).fetchone()[0],
                77,
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*) FROM city_pdf_publication_conflict"
                ).fetchone()[0],
                0,
            )
            self.assertEqual(
                db.execute(
                    "SELECT count(*),md5(string_agg(source_locator||category,'' ORDER BY document_id,source_locator)) "
                    "FROM regional_price"
                ).fetchone(),
                before,
            )

